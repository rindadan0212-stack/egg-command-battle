let made = 0
for (const [name, rows] of Object.entries(ICONS)) {
  const rgba = rasterize(rows)
  const png = encodePng(rgba, SIDE, SIDE)
  const dest = path.join(OUT_DIR, `${name}.png`)
  writeFileSync(dest, png)
  const hash = createHash('sha1').update(png).digest('hex').slice(0, 8)
  console.log(`⭐ ${name}.png  ${SIDE}x${SIDE}  ${png.length}B  sha1:${hash}`)
  made++
}
console.log(`\n${made} 枚 → ${path.relative(process.cwd(), OUT_DIR)}`)
