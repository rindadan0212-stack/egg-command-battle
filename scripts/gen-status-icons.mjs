// ── PNG 書き出し（外部ライブラリ無し・zlib のみ） ─────────────
function crc32(buf) {
  let c
  const table = crc32.table ?? (crc32.table = (() => {
    const t = new Uint32Array(256)
    for (let n = 0; n < 256; n++) {
      c = n
      for (let k = 0; k < 8; k++) c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1)
      t[n] = c >>> 0
    }
    return t
  })())
  let crc = 0xffffffff
  for (let i = 0; i < buf.length; i++) crc = table[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}

function chunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length, 0)
  const typeAndData = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(typeAndData), 0)
  return Buffer.concat([len, typeAndData, crc])
}

/** RGBA の生バイト列（幅×高さ×4）を、白の抜き PNG にする。 */
function encodePng(rgba, width, height) {
  const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])

  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0)
  ihdr.writeUInt32BE(height, 4)
  ihdr[8] = 8    // bit depth
  ihdr[9] = 6    // color type: truecolor + alpha
  ihdr[10] = 0
  ihdr[11] = 0
  ihdr[12] = 0

  // ⚠️ 各行の先頭にフィルタ種別（0＝無し）を1バイト足す（PNG の決まり）
  const stride = width * 4
  const raw = Buffer.alloc((stride + 1) * height)
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, y * stride + stride)
  }
  const idat = deflateSync(raw)

  return Buffer.concat([sig, chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0))])
}

/** 16×16 の `#`/`.` を、整数 SCALE 倍で 128×128 の RGBA へ。⚠️ 補間しない（最近傍）。 */
function rasterize(rows) {
  if (rows.length !== CELL) throw new Error(`絵の行数が ${rows.length}（${CELL} で無いといけない）`)
  for (const row of rows) {
    if (row.length !== CELL) throw new Error(`絵の1行が ${row.length} 文字（「${row}」・${CELL} で無いといけない）`)
  }
  const rgba = Buffer.alloc(SIDE * SIDE * 4)
  for (let cy = 0; cy < CELL; cy++) {
    for (let cx = 0; cx < CELL; cx++) {
      const on = rows[cy][cx] === '#'
      for (let dy = 0; dy < SCALE; dy++) {
        const y = cy * SCALE + dy
        for (let dx = 0; dx < SCALE; dx++) {
          const x = cx * SCALE + dx
          const at = (y * SIDE + x) * 4
          if (on) {
            rgba[at] = 255; rgba[at + 1] = 255; rgba[at + 2] = 255; rgba[at + 3] = 255
          } // ⚠️ else: 0 のまま（透明）── Buffer.alloc は 0 埋め済み
        }
      }
    }
  }
  return rgba
}

