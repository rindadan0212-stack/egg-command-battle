        /// ⭐ ここを揃えておけば、移植元の4本ぶんも自動的に全種族で揃う。</summary>
        // 🔴 **2026-08-26 に 200 → 40。**⭐ 命中・耐性は他の4本と**別の物差し**にした
        //    （`Stats.DebuffScale`）── 通る率の式が引き算なので、桁が揃っている必要が無い。
        //    ⚠️ 揃えていたせいで「何も振っていないアタッカーが既に命中90」になり、
